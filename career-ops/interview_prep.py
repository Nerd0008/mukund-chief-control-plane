def _terms_for(text: str, cfg: dict) -> list[str]:
    wf = cvw.load_config(CONTROL_PLANE / cfg["cv_workflow_config"])
    return cvw.jd_terms(wf, text or "")


def match_evidence(requirement_text: str, evidence: list[dict], cfg: dict) -> list[dict]:
    """Canonical lines that share at least one *specific* term with the requirement.

    A match on a general domain word alone ("security", "data", "analysis") is not
    evidence — it would make almost any requirement look sourced. ``general_terms``
    in the config removes those, and a line only qualifies when a term outside that
    list matches. That is what keeps ``owner_input_required`` honest.
    """
    terms = _terms_for(requirement_text, cfg)
    matching = cfg.get("evidence_matching", {})
    general = {t.casefold() for t in matching.get("general_terms", [])}
    weights = matching.get("section_weight", {})
    scored = []
    for item in evidence:
        hits = cvw.term_hits(item["quote"], terms)
        specific = [h for h in hits if h.casefold() not in general]
        if len(specific) < int(matching.get("min_matched_terms", 1)):
            continue
        scored.append({
            "quote": item["quote"],
            "source": item["source"],
            "source_line": item["source_line"],
            "section": item["section"],
            "matched_terms": specific,
            "score": len(specific) + float(weights.get(item["section"] or "", 0)),
        })
    scored.sort(key=lambda e: (-e["score"], e["source_line"]))
    return scored


def _scaffold_drop(term: str, evidence: list[dict], cfg: dict,
                   used_keys: set[tuple], limit: int = 2) -> list[dict]:
    picked = []
    for item in evidence:
        key = (item["source"], item["source_line"])
        if key in used_keys:
            continue
        if cvw.term_hits(item["quote"], [term]):
            used_keys.add(key)
            picked.append({"quote": item["quote"], "source": item["source"],
                           "source_line": item["source_line"], "section": item["section"],
                           "matched_terms": [term]})
            if len(picked) >= limit:
                break
    return picked


def _education_quotes(evidence: list[dict], used_keys: set[tuple], cfg: dict,
                      limit: int = 2) -> list[dict]:
    """Canonical qualification lines — evidence for a degree/qualification requirement.

    A degree requirement is answered by the canonical qualification material itself;
    the general-term filter that protects every other match would otherwise suppress
    it, because "degree"/"university" appear in almost any posting. The canonical CV
    gives each qualification its own heading, so the section patterns come from the
    config rather than assuming a single "Education" section exists.
    """
    patterns = [p.casefold() for p in
                cfg.get("evidence_matching", {}).get("qualification_section_patterns", [])]
    picked = []
    for item in evidence:
        section = (item["section"] or "").casefold()
        if not any(re.search(p, section) for p in patterns):
            continue
        key = (item["source"], item["source_line"])
        if key in used_keys:
            continue
        used_keys.add(key)
        picked.append({"quote": item["quote"], "source": item["source"],
                       "source_line": item["source_line"], "section": item["section"],
                       "matched_terms": []})
        if len(picked) >= limit:
            break
    return picked


def talking_points(brief: dict, evidence: list[dict], cfg: dict) -> list[dict]:
    """One talking point per essential requirement, quoting canonical lines verbatim."""
    out: list[dict] = []
    used_keys: set[tuple] = set()
    limit = int(_limits(cfg).get("max_talking_points", 12))

    # 1. opening pitch, built only from the canonical Profile line(s)
    profile_line = next((e for e in evidence
                         if (e["section"] or "").casefold() == "profile"), None)
    if profile_line:
        used_keys.add((profile_line["source"], profile_line["source_line"]))
        out.append({
            "id": "tp-opening",
            "use": "opening pitch / 'tell me about yourself'",
            "requirement": None,
            "status": "evidence_backed",
            "quotes": [{"quote": profile_line["quote"], "source": profile_line["source"],
                        "source_line": profile_line["source_line"],
                        "section": profile_line["section"], "matched_terms": []}],
            "scaffold": "Read the canonical profile line aloud, in its own words, then stop. "
                        "Do not add anything the line does not say.",
            "owner_action": None,
        })

    for req in brief.get("requirements", []):
        if req.get("kind") != "essential":
            continue
        if len(out) >= limit:
            break
        category = _category_for(req.get("text"), cfg)["id"]
        if category == "qualification_education":
            quotes = _education_quotes(evidence, used_keys, cfg)
            match_basis = "requirement category 'qualification_education' resolved to the " \
                          "canonical Education section (no term matching used)"
        else:
            ranked = match_evidence(req["text"], evidence, cfg)
            quotes = [q for q in ranked
                      if (q["source"], q["source_line"]) not in used_keys][:2]
            for q in quotes:
                used_keys.add((q["source"], q["source_line"]))
            match_basis = "specific-term overlap against the posting's own vocabulary"
        if quotes:
            out.append({
                "id": f"tp-req-{len(out) + 1}",
                "use": "evidence-backed answer",
                "requirement": {"text": req["text"], "source_line": req["source_line"],
                                "source_section": req.get("source_section")},
                "status": "evidence_backed",
                "match_basis": match_basis,
                "quotes": [{"quote": q["quote"], "source": q["source"],
                            "source_line": q["source_line"], "section": q.get("section"),
                            "matched_terms": q["matched_terms"]}
                           for q in quotes],
                "scaffold": "State plainly what the posting asks for, then quote the canonical "
                            "evidence above. Say what you have not done if the evidence does not "
                            "cover it.",
                "owner_action": None,
            })
        else:
            out.append({
                "id": f"tp-req-{len(out) + 1}",
                "use": "gap to prepare",
                "requirement": {"text": req["text"], "source_line": req["source_line"],
                                "source_section": req.get("source_section")},
                "status": "owner_input_required",
                "match_basis": "no canonical evidence matched",
                "quotes": [],
                "scaffold": "No canonical source in cv.md evidences this requirement.",
                "owner_action": f"Decide how to answer the requirement \"{req['text']}\": either "
                                f"add real evidence to the canonical sources, or prepare to say "
                                f"plainly that you have not done it. This pack will not invent one.",
            })
    return out[:limit]


