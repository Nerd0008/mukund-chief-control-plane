def _category_for(text: str, cfg: dict) -> dict:
    folded = (text or "").casefold()
    for cat in cfg["question_bank"]["categories"]:
        if cat.get("match") and re.search(cat["match"], folded):
            return cat
    return {"id": "general_requirement", "match": None,
            "technical": cfg["question_bank"]["fallback_technical"]}


def technical_questions(brief: dict, cfg: dict) -> list[dict]:
    """One preparation prompt per essential requirement, plus one per responsibility."""
    out: list[dict] = []
    for req in brief.get("requirements", []):
        if req.get("kind") != "essential":
            continue
        category = _category_for(req.get("text"), cfg)
        out.append({
            "id": f"tech-req-{len(out) + 1}",
            "bucket": "technical",
            "category": category["id"],
            "prompt": category["technical"],
            "basis": {
                "kind": "posting_requirement",
                "text": req["text"],
                "source_line": req["source_line"],
                "source_section": req.get("source_section"),
                "requirement_kind": req.get("kind"),
            },
            "derivation": "deterministic template over the posting's own requirement line",
            "employer_supplied": False,
            "note": "This is a preparation prompt generated by this tool, NOT a question the "
                    "employer supplied.",
        })
    for resp in brief.get("responsibilities", []):
        category = _category_for(resp.get("text"), cfg)
        out.append({
            "id": f"tech-resp-{len(out) + 1}",
            "bucket": "technical",
            "category": category["id"],
            "prompt": category["technical"],
            "basis": {
                "kind": "posting_responsibility",
                "text": resp["text"],
                "source_line": resp["source_line"],
                "source_section": resp.get("source_section"),
            },
            "derivation": "deterministic template over the posting's own responsibility line",
            "employer_supplied": False,
            "note": "Preparation prompt generated by this tool, NOT an employer-supplied question.",
        })
    return out[: int(_limits(cfg).get("max_technical_questions", 18))]


def behavioural_questions(brief: dict, cfg: dict) -> list[dict]:
    """Behavioural prompts; each is tied to a posting responsibility when one matches."""
    responsibilities = brief.get("responsibilities", [])
    out: list[dict] = []
    for bank in cfg["question_bank"]["behavioural"]:
        linked = None
        pattern = bank.get("match")
        if pattern:
            for resp in responsibilities:
                if re.search(pattern, (resp.get("text") or "").casefold()):
                    linked = resp
                    break
        out.append({
            "id": f"behav-{bank['id']}",
            "bucket": "behavioural",
            "theme": bank["id"],
            "prompt": bank["question"],
            "basis": ({"kind": "posting_responsibility", "text": linked["text"],
                       "source_line": linked["source_line"],
                       "source_section": linked.get("source_section")} if linked else
                      {"kind": "standard_behavioural_theme", "text": None, "source_line": None,
                       "source_section": None}),
            "derivation": ("deterministic template tied to the posting's own responsibility line"
                           if linked else
                           "standard behavioural theme; no matching responsibility line in this posting"),
            "employer_supplied": False,
            "note": "Preparation prompt generated by this tool, NOT an employer-supplied question.",
        })
    return out[: int(_limits(cfg).get("max_behavioural_questions", 10))]


def motivation_questions(brief: dict, cfg: dict) -> list[dict]:
    job = brief.get("job") or {}
    out = []
    for i, template in enumerate(cfg["question_bank"]["motivation_templates"], start=1):
        out.append({
            "id": f"motiv-{i}",
            "bucket": "motivation",
            "prompt": template,
            "basis": {"kind": "job_record", "text": None, "source_line": None,
                      "source_section": None,
                      "job": {k: job.get(k) for k in ("company", "title", "location")}},
            "derivation": "deterministic template over the job record fields only",
            "employer_supplied": False,
            "note": "Preparation prompt generated by this tool, NOT an employer-supplied question.",
        })
    return out


def eligibility_questions(brief: dict) -> list[dict]:
    out = []
    for i, item in enumerate(brief.get("eligibility", []), start=1):
        out.append({
            "id": f"elig-{i}",
            "bucket": "eligibility",
            "prompt": "The posting states a condition on who may apply. Be ready to state your "
                      "position on it precisely, and do not go beyond what you can evidence.",
            "basis": {"kind": "posting_eligibility", "text": item["text"],
                      "source_line": item["source_line"], "source_section": None,
                      "resolved_status": item.get("status"),
                      "owner_source": item.get("owner_source"),
                      "owner_source_line": item.get("owner_source_line")},
            "derivation": "deterministic template over the posting's own eligibility line",
            "employer_supplied": False,
            "note": "Preparation prompt generated by this tool, NOT an employer-supplied question.",
        })
    return out


def likely_questions(brief: dict, cfg: dict) -> list[dict]:
    items = (technical_questions(brief, cfg) + behavioural_questions(brief, cfg)
             + motivation_questions(brief, cfg) + eligibility_questions(brief))
    return items[: int(_limits(cfg).get("max_likely_questions", 30))]


def questions_to_ask_employer(brief: dict, cfg: dict) -> list[dict]:
    """Drawn only from the brief's own unknowns — never a claim about the employer."""
    out: list[dict] = []
    for item in brief.get("eligibility", []):
        if item.get("status") != "satisfied_by_owner_source":
            out.append({
                "basis": {"kind": "brief_eligibility_unknown", "source_line": item["source_line"],
                          "text": item["text"]},
                "prompt": "Ask how this condition is normally evidenced for this role.",
            })
    for risk in brief.get("risks_unknowns", []):
        if risk.get("severity") in ("major", "blocker"):
            out.append({
                "basis": {"kind": "brief_risk", "detail": risk.get("detail"),
                          "action": risk.get("action")},
                "prompt": "Ask a clarifying question about this uncertainty before relying on it.",
            })
    research = brief.get("research") or {}
    if research.get("status") != "provided":
        out.append({
            "basis": {"kind": "research_gap", "detail": "no cited company research is available"},
            "prompt": "Ask about the team structure, on-call or shift pattern, and what the first "
                      "three months look like — nothing here is known from a source.",
        })
    return out[: int(_limits(cfg).get("max_questions_to_ask_employer", 8))]


