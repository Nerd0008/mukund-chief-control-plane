#!/usr/bin/env python3
"""Interview Prep Agent (roster B22) — role-specific prep from canonical context.

What this is
------------
A deterministic pack builder. It consumes

1. a canonical **JobBrief** produced by ``career-ops/job_intelligence.py``
   (verbatim posting lines with source lines, eligibility resolution, risks and
   cited company facts),
2. the canonical owner sources inside the existing Career Ops install
   (``cv.md``, ``config/profile.yml``, ``config/cv-facts.json``), and
3. optionally a cited research file through the briefing module's own provider
   interface (``job_intelligence.research_brief``),

and produces, for one role:

* technical preparation prompts derived from the posting's own requirement lines,
* behavioural preparation prompts tied to the posting's responsibility lines,
* a likely-question list,
* evidence-backed talking points that quote canonical CV lines verbatim,
* questions to ask the employer drawn from the brief's own unknowns,
* an explicit unknown / owner-input list.

Truth rules (enforced, not decorative)
-------------------------------------
* A question is a **preparation prompt generated by a deterministic template**.
  It is never presented as a question the employer supplied, and every question
  item carries that disclaimer plus the verbatim posting line it came from.
* A talking point **quotes a canonical CV line verbatim** and carries its
  ``cv.md`` source line. Nothing is paraphrased, summarised or extended.
* Where the posting asks for something the canonical sources do not evidence,
  the result is ``owner_input_required`` — never a claim about the candidate.
  ``candidate_claims`` is always empty and a first-person-claim scanner fails
  the pack if one ever appears in generated text.
* Company/role context comes only from the brief's cited facts. With no provider
  the pack records ``research_needed`` and adds no company fact.
* No employer, recruiter or candidate is contacted; nothing is posted, sent,
  scheduled or submitted; no browser, GUI or network call is made.

CLI
  python career-ops/interview_prep.py pack --brief BRIEF.json [--research-file F]
                                        [--out DIR] [--stamp S]
  python career-ops/interview_prep.py from-job --region uk --jd-file JD.txt
                                        [--id ID | --url URL | --row N
                                         | --pipeline-index N | --job-record REC.json]
                                        [--research-file F] [--out DIR] [--stamp S]
  python career-ops/interview_prep.py validate --pack PACK.json
  python career-ops/interview_prep.py schema
  python career-ops/interview_prep.py status

Input and output paths stay separate: ``--brief``/``--jd-file``/``--job-record``/
``--research-file`` are read-only and the command refuses to run if an output
path would overwrite one of its own inputs.
"""

