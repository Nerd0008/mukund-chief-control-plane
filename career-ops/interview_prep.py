def collect_unknowns(brief: dict, talking: list[dict], cfg: dict) -> list[dict]:
    out: list[dict] = []
    for item in brief.get("eligibility", []):
        if item.get("status") != "satisfied_by_owner_source":
            out.append({"kind": "eligibility_unknown", "detail": item["text"],
                        "source": f"JobBrief eligibility line {item['source_line']}",
                        "action": "State your position yourself; the build will not infer it."})
    for risk in brief.get("risks_unknowns", []):
        out.append({"kind": f"brief_risk:{risk.get('kind')}", "detail": risk.get("detail"),
                    "source": "JobBrief risks_unknowns",
                    "action": risk.get("action"),
                    "severity": risk.get("severity")})
    research = brief.get("research") or {}
    if research.get("status") != "provided":
        out.append({"kind": "research_needed",
                    "detail": "No cited company/role research is available for this posting.",
                    "source": "JobBrief research.status",
                    "action": "Supply a cited research file, or ask these questions in the "
                              "interview rather than assuming an answer."})
    for tp in talking:
        if tp["status"] == "owner_input_required":
            out.append({"kind": "requirement_without_canonical_evidence",
                        "detail": tp["requirement"]["text"],
                        "source": f"JobBrief requirement line {tp['requirement']['source_line']}",
                        "action": tp["owner_action"]})
    return out[: int(_limits(cfg).get("max_unknowns", 40))]


def candidate_claim_violations(pack: dict) -> list[dict]:
    """Scan generated (non-quoted) text for a candidate claim that was never sourced.

    Quoted canonical lines are excluded by construction: only ``prompt``,
    ``scaffold``, ``note``, ``owner_action``, ``use`` and ``derivation`` fields are
    scanned, and none of them may contain a first-person claim pattern.
    """
    violations: list[dict] = []
    scanned_fields = ("prompt", "scaffold", "note", "owner_action", "use", "derivation",
                      "theme", "category")
    sections = [
        ("sections.technical_prep", pack.get("sections", {}).get("technical_prep", [])),
        ("sections.behavioural_prep", pack.get("sections", {}).get("behavioural_prep", [])),
        ("sections.likely_questions", pack.get("sections", {}).get("likely_questions", [])),
        ("sections.evidence_backed_talking_points",
         pack.get("sections", {}).get("evidence_backed_talking_points", [])),
        ("sections.questions_to_ask_employer",
         pack.get("sections", {}).get("questions_to_ask_employer", [])),
    ]
    for where, items in sections:
        for item in items:
            for field in scanned_fields:
                value = item.get(field)
                if not isinstance(value, str):
                    continue
                for pattern in ji.CANDIDATE_CLAIM_PATTERNS:
                    if re.search(pattern, value, re.I):
                        violations.append({"where": where, "id": item.get("id"),
                                           "field": field, "pattern": pattern,
                                           "text": value[:200]})
    return violations


def quote_violations(pack: dict, cfg: dict) -> list[dict]:
    """Every quoted line must exist verbatim at the cv.md line it claims."""
    index = canonical_line_index(cfg)
    bad: list[dict] = []
    for tp in pack.get("sections", {}).get("evidence_backed_talking_points", []):
        for q in tp.get("quotes", []):
            actual = index.get(q.get("source_line"))
            if actual is None:
                bad.append({"id": tp.get("id"), "reason": "source line does not exist",
                            "source_line": q.get("source_line")})
                continue
            stripped = actual[1:].strip() if actual.startswith(("-", "*")) else actual
            if q.get("quote") != stripped:
                bad.append({"id": tp.get("id"), "reason": "quote is not verbatim at that line",
                            "source_line": q.get("source_line"),
                            "expected": stripped[:160], "got": str(q.get("quote"))[:160]})
    return bad


