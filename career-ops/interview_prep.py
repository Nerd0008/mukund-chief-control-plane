def build_prep_pack(cfg: dict, brief: dict, *, brief_path: str | Path | None = None,
                    research_file: str | Path | None = None,
                    stamp: str | None = None) -> dict:
    stamp = stamp or dt.datetime.now(dt.timezone.utc).strftime("%Y%m%dT%H%M%SZ")
    evidence = canonical_evidence(cfg)

    research_facts = brief.get("company_facts", [])
    research_meta = dict(brief.get("research") or {})
    research_source = "JobBrief (career-ops/job_intelligence.py)"
    if research_file:
        extra = ji.research_brief(ji_config(cfg), brief.get("job") or {},
                                  research_file=research_file)
        research_facts = extra.get("facts", [])
        research_meta = {k: v for k, v in extra.items() if k != "facts"}
        research_source = f"research file {research_file} via job_intelligence.research_brief"

    tech = technical_questions(brief, cfg)
    behav = behavioural_questions(brief, cfg)
    likely = likely_questions(brief, cfg)
    talking = talking_points(brief, evidence, cfg)
    employer_q = questions_to_ask_employer(brief, cfg)
    unknowns = collect_unknowns(brief, talking, cfg)

    cv_paths = cvw.source_paths(cv_config(cfg))
    job_key = sha256_text(json.dumps(brief.get("job") or {}, sort_keys=True))[:8]
    pack = {
        "schema_version": cfg.get("schema_version", 1),
        "prep_id": f"ip-{stamp}-{job_key}",
        "generated_at": now_utc(),
        "generator": "career-ops/interview_prep.py",
        "job": brief.get("job"),
        "provenance": {
            "brief": {"path": str(brief_path) if brief_path else None,
                      "brief_id": brief.get("brief_id"),
                      "sha256": sha256_file(brief_path) if brief_path else None,
                      "generator": brief.get("generator"),
                      "job_description": (brief.get("provenance") or {}).get("job_description")},
            "canonical_owner_sources": {
                "cv.md": {"path": str(cv_paths["cv_md"]), "sha256": sha256_file(cv_paths["cv_md"])},
                "config/profile.yml": {"path": str(cv_paths["profile"]),
                                       "sha256": sha256_file(cv_paths["profile"])},
                "config/cv-facts.json": {"path": str(cv_paths["cv_facts"]),
                                         "sha256": sha256_file(cv_paths["cv_facts"])},
            },
            "canonical_evidence_lines": len(evidence),
            "research_source": research_source,
            "question_derivation": "deterministic templates over the posting's own text "
                                   "(career-ops/interview_prep_config.json question_bank)",
        },
        "research": {**research_meta, "facts_available": len(research_facts),
                     "facts": research_facts},
        "sections": {
            "technical_prep": tech,
            "behavioural_prep": behav,
            "likely_questions": likely,
            "evidence_backed_talking_points": talking,
            "questions_to_ask_employer": employer_q,
            "unknowns": unknowns,
        },
        "counts": {
            "technical_prep": len(tech),
            "behavioural_prep": len(behav),
            "likely_questions": len(likely),
            "talking_points": len(talking),
            "talking_points_evidence_backed": sum(1 for t in talking
                                                  if t["status"] == "evidence_backed"),
            "talking_points_owner_input_required": sum(1 for t in talking
                                                       if t["status"] == "owner_input_required"),
            "questions_to_ask_employer": len(employer_q),
            "unknowns": len(unknowns),
            "source_lines_quoted": sum(len(t.get("quotes", [])) for t in talking),
        },
        "truth_rules": cfg.get("truth_rules", []),
        "candidate_claims": [],
        "not_performed": cfg.get("not_performed", []),
        "external_actions_taken": [],
        "interview_scheduled": False,
        "interview_attended": False,
    }
    pack["validation"] = validate_pack(pack, cfg)
    pack["candidate_claim_violations"] = candidate_claim_violations(pack)
    pack["quote_violations"] = quote_violations(pack, cfg)
    pack["ok"] = bool(pack["validation"]["ok"]) and not pack["candidate_claim_violations"] \
        and not pack["quote_violations"]
    return pack


def validate_pack(pack: dict, cfg: dict | None = None) -> dict:
    """Structural + truth checks, independent of how the pack was produced."""
    errors: list[str] = []
    warnings: list[str] = []

    for key in ("schema_version", "prep_id", "generated_at", "generator", "job",
                "provenance", "sections", "counts", "candidate_claims",
                "not_performed", "external_actions_taken"):
        if key not in pack:
            errors.append(f"missing required key: {key}")
    if not isinstance(pack.get("job"), dict):
        errors.append("job must be an object")
    else:
        for key in ("title", "company"):
            if not pack["job"].get(key):
                warnings.append(f"job.{key} is not stated in the brief")

    sections = pack.get("sections") or {}
    for name in ("technical_prep", "behavioural_prep", "likely_questions",
                 "evidence_backed_talking_points", "questions_to_ask_employer", "unknowns"):
        if not isinstance(sections.get(name), list):
            errors.append(f"sections.{name} must be a list")

    for item in sections.get("likely_questions", []) or []:
        for key in ("id", "bucket", "prompt", "basis", "derivation", "employer_supplied",
                    "note"):
            if key not in item:
                errors.append(f"question {item.get('id')} missing {key}")
        if item.get("employer_supplied") is not False:
            errors.append(f"question {item.get('id')} claims to be employer-supplied")
        if "NOT" not in (item.get("note") or ""):
            errors.append(f"question {item.get('id')} does not disclaim employer origin")

    for tp in sections.get("evidence_backed_talking_points", []) or []:
        for key in ("id", "use", "status", "quotes", "scaffold"):
            if key not in tp:
                errors.append(f"talking point {tp.get('id')} missing {key}")
        if tp.get("status") not in ("evidence_backed", "owner_input_required"):
            errors.append(f"talking point {tp.get('id')} has an unknown status")
        if tp.get("status") == "evidence_backed" and not tp.get("quotes"):
            errors.append(f"talking point {tp.get('id')} claims evidence with no quote")
        if tp.get("status") == "owner_input_required" and not tp.get("owner_action"):
            errors.append(f"talking point {tp.get('id')} has no owner action")
        for q in tp.get("quotes", []) or []:
            for key in ("quote", "source", "source_line"):
                if key not in q:
                    errors.append(f"talking point {tp.get('id')} quote missing {key}")

    if pack.get("candidate_claims"):
        errors.append("candidate_claims must be empty")
    if pack.get("external_actions_taken"):
        errors.append("external_actions_taken must be empty")
    if pack.get("interview_scheduled") or pack.get("interview_attended"):
        errors.append("the prep agent must never record a scheduled or attended interview")

    return {"ok": not errors, "errors": errors, "warnings": warnings,
            "checked_sections": list(sections.keys())}


