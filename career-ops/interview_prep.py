def _refuse_to_overwrite_inputs(args, out_paths: list[Path]) -> list[dict]:
    inputs = []
    for attr in ("brief", "jd_file", "job_record", "research_file"):
        value = getattr(args, attr, None)
        if value:
            inputs.append((attr, Path(value).resolve()))
    problems = []
    for flag, inp in inputs:
        for out in out_paths:
            if out.resolve() == inp:
                problems.append({"input_flag": flag, "path": str(inp),
                                 "reason": "output path would overwrite an input file"})
    return problems


def _write_pack(pack: dict, out_dir: Path) -> dict:
    out_dir.mkdir(parents=True, exist_ok=True)
    pack_path = out_dir / "interview_prep_pack.json"
    pack_path.write_text(json.dumps(pack, indent=2, ensure_ascii=False, default=str),
                         encoding="utf-8")
    md = [f"# Interview prep pack — {pack['prep_id']}", "",
          f"Generated: {pack['generated_at']}",
          f"Role: {pack.get('job', {}).get('title')} @ {pack.get('job', {}).get('company')}",
          f"Brief: {pack['provenance']['brief'].get('brief_id')}",
          "",
          "Every question below is a preparation prompt generated by a deterministic",
          "template from the posting's own text. None of them is a question the",
          "employer supplied. Nothing here was sent to anyone.", ""]
    for name, items in (("Technical preparation", pack["sections"]["technical_prep"]),
                        ("Behavioural preparation", pack["sections"]["behavioural_prep"])):
        md += [f"## {name}", ""]
        for item in items:
            md.append(f"- **{item['id']}** {item['prompt']}")
            basis = item.get("basis") or {}
            if basis.get("text"):
                md.append(f"  - posting line {basis['source_line']}: {basis['text']}")
        md.append("")
    md += ["## Likely questions (index — full detail in the sections above)", ""]
    for n, item in enumerate(pack["sections"]["likely_questions"], start=1):
        basis = item.get("basis") or {}
        suffix = (f"  (posting line {basis['source_line']})" if basis.get("source_line")
                  else "  (not posting-derived)")
        md.append(f"{n}. [{item['bucket']}/{item['id']}] {item['prompt']}{suffix}")
    md.append("")
    md += ["## Evidence-backed talking points", ""]
    for tp in pack["sections"]["evidence_backed_talking_points"]:
        md.append(f"- **{tp['id']}** ({tp['status']}) — {tp['use']}")
        if tp.get("requirement"):
            md.append(f"  - posting line {tp['requirement']['source_line']}: "
                      f"{tp['requirement']['text']}")
        for q in tp.get("quotes", []):
            md.append(f"  - cv.md:{q['source_line']} — {q['quote']}")
        if tp.get("owner_action"):
            md.append(f"  - owner action: {tp['owner_action']}")
    md += ["", "## Unknowns", ""]
    md += [f"- ({u['kind']}) {u.get('detail')}" for u in pack["sections"]["unknowns"]]
    (out_dir / "interview_prep_pack.md").write_text("\n".join(md) + "\n", encoding="utf-8")
    return {"pack_path": str(pack_path), "pack_markdown": str(out_dir / "interview_prep_pack.md")}


def cmd_pack(args) -> int:
    cfg = load_config(args.config)
    try:
        brief = load_brief(args.brief)
    except (BriefError, json.JSONDecodeError) as exc:
        emit({"ok": False, "reason": f"{type(exc).__name__}: {exc}"})
        return 1
    stamp = args.stamp or dt.datetime.now(dt.timezone.utc).strftime("%Y%m%dT%H%M%SZ")
    out_dir = Path(args.out) if args.out else (runtime_dir(cfg) / stamp)
    collisions = _refuse_to_overwrite_inputs(args, [out_dir / "interview_prep_pack.json",
                                                    out_dir / "interview_prep_pack.md"])
    if collisions:
        emit({"ok": False, "reason": "refusing to write over an input file",
              "collisions": collisions, "writes_performed": []})
        return 1
    pack = build_prep_pack(cfg, brief, brief_path=args.brief,
                           research_file=args.research_file, stamp=stamp)
    paths = _write_pack(pack, out_dir)
    emit({"ok": pack["ok"], **paths, "prep_id": pack["prep_id"], "job": pack["job"],
          "counts": pack["counts"], "validation": pack["validation"],
          "candidate_claim_violations": pack["candidate_claim_violations"],
          "quote_violations": pack["quote_violations"],
          "external_actions_taken": []})
    return 0 if pack["ok"] else 1


def cmd_from_job(args) -> int:
    """Resolve a job from Career Ops, brief it, then build the prep pack."""
    cfg = load_config(args.config)
    wf = cvw.load_config(CONTROL_PLANE / cfg["cv_workflow_config"])
    profiles = tw.load_profiles(str(profiles_path(cfg)))
    resolved = cvw.resolve_job(wf, profiles, region=args.region, job_id=args.id,
                               url=args.url, row=args.row,
                               pipeline_index=args.pipeline_index,
                               record_file=args.job_record)
    if not resolved.get("ok"):
        emit(resolved)
        return 1
    job = resolved["job"]
    if args.jd_file:
        p = Path(args.jd_file)
        if not p.exists():
            emit({"ok": False, "reason": f"job-description file not found: {p}"})
            return 1
        jd_text = read_text(p)
        jd_source = f"explicit file {p}"
    else:
        jd_text = resolved.get("jd_text") or ""
        jd_source = resolved.get("jd_source")
    stamp = args.stamp or dt.datetime.now(dt.timezone.utc).strftime("%Y%m%dT%H%M%SZ")
    brief = ji.build_brief(ji_config(cfg), job=job, jd_text=jd_text, jd_source=jd_source,
                           research_file=args.research_file, stamp=stamp)
    out_dir = Path(args.out) if args.out else (runtime_dir(cfg) / stamp)
    collisions = _refuse_to_overwrite_inputs(args, [out_dir / "interview_prep_pack.json",
                                                    out_dir / "interview_prep_pack.md"])
    if collisions:
        emit({"ok": False, "reason": "refusing to write over an input file",
              "collisions": collisions, "writes_performed": []})
        return 1
    brief_path = out_dir / "job_brief.json"
    out_dir.mkdir(parents=True, exist_ok=True)
    brief_path.write_text(json.dumps(brief, indent=2, ensure_ascii=False, default=str),
                          encoding="utf-8")
    pack = build_prep_pack(cfg, brief, brief_path=brief_path, stamp=stamp)
    paths = _write_pack(pack, out_dir)
    emit({"ok": pack["ok"], "brief_path": str(brief_path), **paths,
          "prep_id": pack["prep_id"], "job": pack["job"], "counts": pack["counts"],
          "brief_validation_ok": brief["validation"]["ok"],
          "validation": pack["validation"],
          "candidate_claim_violations": pack["candidate_claim_violations"],
          "quote_violations": pack["quote_violations"],
          "external_actions_taken": []})
    return 0 if pack["ok"] else 1


def cmd_validate(args) -> int:
    cfg = load_config(args.config)
    pack = json.loads(read_text(args.pack))
    # Re-derive the truth checks against the live canonical sources so a pack
    # cannot be validated against its own claims.
    result = validate_pack(pack, cfg)
    try:
        result["quote_violations"] = quote_violations(pack, cfg)
    except Exception as exc:  # noqa: BLE001 - absent install is reported truthfully
        result["quote_violations"] = []
        result["quote_check_error"] = f"{type(exc).__name__}: {exc}"
    result["candidate_claim_violations"] = candidate_claim_violations(pack)
    result["ok"] = bool(result["ok"]) and not result["quote_violations"] \
        and not result["candidate_claim_violations"]
    emit(result)
    return 0 if result["ok"] else 1


