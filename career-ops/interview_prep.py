def cmd_status(args) -> int:
    cfg = load_config(args.config)
    cv_paths = cvw.source_paths(cv_config(cfg))
    runtime = runtime_dir(cfg)
    packs = sorted(runtime.glob("*/interview_prep_pack.json")) if runtime.exists() else []
    return_status = {
        "ok": True,
        "generated_at": now_utc(),
        "config": cfg["_config_path"],
        "runtime_dir": str(runtime),
        "packs_built": len(packs),
        "latest_pack": str(packs[-1]) if packs else None,
        "canonical_sources": {k: {"path": str(p), "exists": p.exists()} for k, p in cv_paths.items()},
        "question_bank_categories": [c["id"] for c in cfg["question_bank"]["categories"]],
        "behavioural_themes": [b["id"] for b in cfg["question_bank"]["behavioural"]],
        "not_performed": cfg["not_performed"],
        "external_actions_available": [],
    }
    emit(return_status)
    return 0


