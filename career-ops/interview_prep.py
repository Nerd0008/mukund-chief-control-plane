class BriefError(ValueError):
    """The supplied document is not usable as a JobBrief."""


def load_brief(path: str | Path) -> dict:
    """Read a JobBrief and refuse anything that is not one.

    The prep pack's whole provenance chain depends on the brief being the
    extractive artifact ``job_intelligence.py`` produced, so a file that merely
    *looks* like JSON is rejected rather than guessed at.
    """
    p = Path(path)
    if not p.exists():
        raise BriefError(f"brief not found: {p}")
    doc = json.loads(read_text(p))
    if not isinstance(doc, dict):
        raise BriefError("brief must be a JSON object")
    missing = [k for k in ("brief_id", "job", "requirements", "eligibility",
                           "source_supported_facts") if k not in doc]
    if missing:
        raise BriefError(
            "not a JobBrief: missing " + ", ".join(missing)
            + " (produce one with career-ops/job_intelligence.py brief)")
    if doc.get("candidate_claims"):
        raise BriefError("brief carries candidate_claims, which must be empty")
    return doc


def canonical_evidence(cfg: dict) -> list[dict]:
    """Every non-empty canonical CV line, with its cv.md line number."""
    cv_path = cvw.source_paths(cv_config(cfg))["cv_md"]
    text = read_text(cv_path)
    out: list[dict] = []
    for section in cvw.parse_cv_markdown(text):
        for line in section["lines"]:
            if line["kind"] == "blank" or not line["text"].strip():
                continue
            out.append({
                "quote": line["text"],
                "source": QUOTE_SOURCE,
                "source_line": line["no"],
                "section": section["heading"],
                "kind": line["kind"],
            })
    return out


def canonical_line_index(cfg: dict) -> dict[int, str]:
    cv_path = cvw.source_paths(cv_config(cfg))["cv_md"]
    index = {}
    for no, raw in enumerate(read_text(cv_path).splitlines(), start=1):
        index[no] = raw.strip()
    return index


